#!/bin/sh
# Install the "webui" channel into Letta Code's user channel directory.
#
# Writes only ~/.letta/channels/webui/{channel.json,plugin.mjs,accounts.json}.
# plugin.mjs is a stub that re-exports src/plugin.mjs from this repo, so later
# `git pull`s take effect after a server restart. An existing accounts.json is
# kept as is.
#
# Env overrides: LETTA_UI_PORT (default 4610), LETTA_UI_SENDER_ID (default $USER),
# LETTA_UI_SENDER_NAME (default: your macOS full name, else $USER).
set -eu

REPO_DIR=$(cd "$(dirname "$0")/.." && pwd)
CHANNEL_DIR="$HOME/.letta/channels/webui"
PORT="${LETTA_UI_PORT:-4610}"
SENDER_ID="${LETTA_UI_SENDER_ID:-${USER:-user}}"
SENDER_NAME="${LETTA_UI_SENDER_NAME:-$(id -F 2>/dev/null || echo "$SENDER_ID")}"

mkdir -p "$CHANNEL_DIR"

cat > "$CHANNEL_DIR/channel.json" <<EOF
{
  "id": "webui",
  "displayName": "Web UI",
  "entry": "./plugin.mjs",
  "runtimePackages": [],
  "runtimeModules": []
}
EOF

cat > "$CHANNEL_DIR/plugin.mjs" <<EOF
// Stub generated by letta-ui/scripts/install.sh. The real plugin lives in the repo.
export * from "$REPO_DIR/src/plugin.mjs";
export { default } from "$REPO_DIR/src/plugin.mjs";
EOF

if [ -f "$CHANNEL_DIR/accounts.json" ]; then
  echo "Keeping existing $CHANNEL_DIR/accounts.json"
else
  NOW=$(date -u +%Y-%m-%dT%H:%M:%S.000Z)
  cat > "$CHANNEL_DIR/accounts.json" <<EOF
{
  "accounts": [
    {
      "channel": "webui",
      "accountId": "webui-local",
      "displayName": "Web UI",
      "enabled": true,
      "dmPolicy": "allowlist",
      "allowedUsers": ["$SENDER_ID"],
      "config": { "port": $PORT, "sender_id": "$SENDER_ID", "sender_name": "$SENDER_NAME" },
      "createdAt": "$NOW",
      "updatedAt": "$NOW"
    }
  ]
}
EOF
  echo "Created $CHANNEL_DIR/accounts.json (port $PORT, sender $SENDER_ID)"
fi

echo "Installed webui channel -> $REPO_DIR"
echo
echo "Next:"
echo "  letta server --backend local --channels webui"
echo "  open http://127.0.0.1:$PORT   (then press \"+ New\" next to an agent)"
